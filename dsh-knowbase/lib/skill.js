export const SKILL_NAME = 'knowledge-base'

export const SKILL_CONTENT = `# 本地知识库

本机装了一个本地知识库插件。它把用户自己的文档切成片段、建成索引，
支持关键词与语义混合检索，所有数据都在用户电脑上。

## 什么时候必须用 kb_search

**默认先查，再回答。** 遇到下列情况必须调用 \`kb_search\`：

- 用户问的是他自己的资料：「我的文档里」「那份报告」「上次那篇论文」
- 问题涉及具体事实、数字、条款、定义，而用户库里有相关专题
- 用户要求「根据我的资料」「引用出处」「找出处」
- 你不确定答案、可能记错时——查一次比编一个强

**可以不查的情况**：闲聊、纯代码问题、用户明确说「不用查库」。

**查不到怎么办**：如实说「你的库里没有这方面的资料」，
不要假装查过，也不要把通用知识说成来自用户的库。

## 检索结果怎么用

\`kb_search\` 返回的每条命中都带：

| 字段 | 含义 |
|---|---|
| \`title\` | 文档名 |
| \`page\` | 页码（PDF/PPT 有，纯文本为空） |
| \`text\` | 原文片段 |
| \`similarity\` | 语义相似度 0–1 |

回答时**必须写出处**，格式：

> 根据《书名》第 12 页，……

多个来源就分别标注。页码缺失时只写文档名。

## 建一个专题库（五步法）

用户说「帮我建一个 XX 库」时按这个顺序：

1. **定主题**：和用户确认库名与范围，例如「自然科学基础」「马列经典原著」
2. **找来源**：优先用公开权威站点（见下），不要抓付费墙或需要登录的内容
3. **取资料**：用 \`kb_source_fetch\` 抓单个网页，或让用户手动拖入文件
4. **入库并建索引**：\`kb_ingest\` 导入文件；向量索引由界面上的
   「建立向量索引」完成，或提示用户去点
5. **抽检验证**：用 \`kb_search\` 提几个问题，确认能查到；查不到就换关键词或补资料

**导入格式**：PDF、Word（.docx）、PPT（.pptx）、Excel（.xlsx）、Markdown、TXT、HTML。
旧版 .doc / .ppt / .xls 需要先另存为新格式。

## 抓取资料的纪律

\`kb_source_fetch\` 只抓公开可访问的页面，并且：

- 遇到登录、付费、验证码会失败——**不要试图绕过**，把链接给用户让他自己决定
- 抓来的文档会记录来源 URL 与时间，引用时可以一并说明
- 一次别抓太多，抓完先检索验证质量

### 可优先考虑的公开来源

自然科学与综合：

- arXiv（预印本，引用时要标注「预印本」）
- PubMed Central 开放获取子集
- OpenStax、LibreTexts（开放教材，注意 CC 许可条款）
- 国家统计局、国家标准全文公开系统

人文社科：

- 求是网、中央党史和文献研究院（公开文献）
- 国家哲学社会科学文献中心（NCPSSD，注册后免费）

**许可提醒**：教材类多为 CC BY / CC BY-NC-SA，国家标准不得商用转载。
不确定时告诉用户「这份资料的许可需要你自己确认」。

## 工具清单

| 工具 | 用途 |
|---|---|
| \`kb_list\` | 看有哪些库、某库有哪些文档、索引状态 |
| \`kb_search\` | 检索，返回片段与出处（最常用） |
| \`kb_ingest\` | 把文件或目录导入某个库 |
| \`kb_source_fetch\` | 抓一个公开网址入库 |
| \`kb_job\` | 查长任务进度 |

## 常见误用

- ❌ 没查就说「根据你的文档」——这是编造
- ❌ 把检索到的片段原样粘贴一大段——应该提炼要点并标注出处
- ❌ 用户库里没有的内容，说成「你的资料显示」——应说明是通用知识
- ❌ 抓取失败还反复重试同一个需要登录的站点
`

